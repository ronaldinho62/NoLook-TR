export type Strings = typeof en;

/// Türkçe sürüm: tarayıcı dili İngilizce değilse Türkçe
export function stringsFor(rules: Rules | undefined): Strings {
  const lang = rules?.settings?.lang ?? (navigator.language.toLowerCase().startsWith('en') ? 'en' : 'tr');
  return lang === 'tr' ? trStrings : en;
}
